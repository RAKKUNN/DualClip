/* Prerenders the landing page to static HTML.
 *
 * The page used to ship React + ReactDOM (development builds) and
 * @babel/standalone to every visitor and transpile JSX in the browser —
 * roughly 2.5 MB of JavaScript before the first pixel, and an empty <body>
 * for anything that doesn't run scripts. Now React runs here at build time
 * and the browser gets HTML plus a small site.js.
 *
 *   npm install && npm run build      (from docs/)
 *
 * index.html is generated. Edit index.template.html and the components.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createContext, runInContext } from 'node:vm';

import { transformSync } from '@babel/core';
import presetReact from '@babel/preset-react';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

const here = dirname(fileURLToPath(import.meta.url));

// Order matters: each file publishes its components onto `window`.
const SOURCES = [
  'components/primitives.jsx',
  'components/hero.jsx',
  'components/sections.jsx',
  'app.jsx'
];

const MARKER = '<!--APP-->';

function compile(file) {
  const source = readFileSync(join(here, file), 'utf8');
  const { code } = transformSync(source, {
    filename: file,
    presets: [[presetReact, { runtime: 'classic' }]],
    configFile: false,
    babelrc: false
  });
  return code;
}

function render() {
  // A bare `window` is enough: the components only touch React and each other.
  // Anything reaching for real DOM APIs at module scope is a bug for a
  // prerendered page, and will throw here rather than silently ship broken.
  const sandbox = { React, console };
  sandbox.window = sandbox;
  sandbox.globalThis = sandbox;
  const context = createContext(sandbox);

  for (const file of SOURCES) {
    try {
      runInContext(compile(file), context, { filename: file });
    } catch (error) {
      throw new Error(`failed evaluating ${file}: ${error.message}`);
    }
  }

  if (typeof sandbox.App !== 'function') {
    throw new Error('app.jsx did not put an App component on window');
  }
  return renderToStaticMarkup(React.createElement(sandbox.App));
}

const template = readFileSync(join(here, 'index.template.html'), 'utf8');
if (!template.includes(MARKER)) {
  throw new Error(`index.template.html is missing the ${MARKER} marker`);
}

const html = template.replace(
  MARKER,
  `<!-- Generated by build.mjs — edit index.template.html instead -->\n${render()}`
);

writeFileSync(join(here, 'index.html'), html);

const kb = (Buffer.byteLength(html) / 1024).toFixed(1);
console.log(`index.html written (${kb} kB)`);
